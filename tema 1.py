from math import comb, factorial

# 1.8 — 10 фильмов по 5 номинациям
print(f"1.8 а) 10^5 = {10**5}")
print(f"1.8 б) C(14,5) = {comb(14, 5)}")

# 1.9 — Перестановки (цифры 4, 5, 6)
print(f"1.9 7! / (3! * 2! * 2!) = {factorial(7) // (factorial(3) * factorial(2) * factorial(2))}")

# 1.10 — Вероятность слова "ТЕОРИЯ"
print(f"1.10 а) 1 / 6! = {1 / factorial(6):.6f}")
print(f"1.10 б) 1/6 * 1/5 * 1/4 * 1/3 * 1/2 * 1/1 = {1/6 * 1/5 * 1/4 * 1/3 * 1/2 * 1/1:.6f}")

# 1.11 — Вероятность слова "АНАНАС"
print(f"1.11 1 / (6! / (3! * 2! * 1!)) = {1 / (factorial(6) // (factorial(3) * factorial(2) * factorial(1))):.6f}")

# 1.16 — 5 мужчин и 5 женщин за круглым столом
print(f"1.16 а) (2 * 5! * 5!) / 9! = {(2 * factorial(5) * factorial(5)) / factorial(9):.5f}")
print(f"1.16 б) (5! * 2^5) / 9! = {(factorial(5) * 2**5) / factorial(9):.5f}")

# 1.17 — 7 пассажиров в купейном вагоне (9 купе × 4 места)
n = comb(36, 7)

# а) 7 человек в 2 купе
m_a = comb(9, 2) * (comb(4, 3) * comb(4, 4) + comb(4, 4) * comb(4, 3))
print(f"1.17 а) (C(9,2) * 8) / C(36,7) = {m_a / n:.7f}")

# б) 7 человек в 7 разных купе
m_b = comb(9, 7) * 4**7
print(f"1.17 б) (C(9,7) * 4^7) / C(36,7) = {m_b / n:.5f}")

# в) 7 человек в 3 купе
t1 = 6 * comb(4, 1) * comb(4, 2) * comb(4, 4)
t2 = 3 * comb(4, 1) * comb(4, 3) * comb(4, 3)
t3 = 3 * comb(4, 2) * comb(4, 2) * comb(4, 3)
m_d = comb(9, 3) * (t1 + t2 + t3)
print(f"1.17 в) (C(9,3) * ({t1}+{t2}+{t3})) / C(36,7) = {m_d / n:.5f}")